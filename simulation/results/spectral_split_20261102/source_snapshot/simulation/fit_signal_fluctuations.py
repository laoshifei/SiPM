"""Fit a conditional stochastic readout correction on run3/12 training only.

The average impulse is regenerated by the native C++ kernel. Residual FIR power
is estimated from conditional pulse-minus-baseline spectra, never from a copied
waveform. This is a per-acquisition empirical calibration, not a unique circuit.
"""
import json
from pathlib import Path
import numpy as np
import ROOT
from calibrate_signal_fluctuations import OUT,PARENT,BASE,diagnostic,save
from reference import PROJECT,aligned_shapes,TIME_NS,wave_features
from diagnose_fluctuations import fluctuation_metrics
from diagnose_charge import sha

RCS=[94.47173460998194,100.,105.,110.,125.,145.,170.]
REGION=(TIME_NS>=-100)&(TIME_NS<=3500)


def fir_from_power(freq,power):
    # Finite400ns diagnostic cannot constrain lower frequencies; continue the
    # first5MHz estimate flat to zero. Preserve negative estimates in reports.
    spectral=np.maximum(power,0.)
    spectral[:2]=spectral[2]
    fft_n=2048
    f=np.fft.rfftfreq(fft_n,2.)*1000
    target=np.interp(f,freq,spectral)
    h=np.fft.fftshift(np.fft.irfft(np.sqrt(target),n=fft_n))
    h=h[fft_n//2-128:fft_n//2+129]*np.hanning(257)
    if not np.isfinite(h).all() or np.dot(h,h)<=0:raise ValueError('No positive residual power')
    return h


def colored(h,noise):
    # noise has independent prehistory for every event, as native implementation.
    n=noise.shape[1];size=1<<(n+len(h)-2).bit_length()
    return np.fft.irfft(np.fft.rfft(noise,n=size)*np.fft.rfft(h,n=size),n=size)[:,len(h)-1:n]


def main():
    design=json.loads((OUT/'design.json').read_text());edges=np.array(design['q_edges'])
    report={'scope':__doc__,'code_sha256':sha(Path(__file__)),'prepare_design_sha256':sha(OUT/'design.json'),
      'training_ids':'Frozen run3/12 first60. No other segment used for tuning.',
      'grid_RC_ns':RCS,'residual_method':'Conditional Hann spectra,three400ns windows at500,1200,2200ns minus equal-length pretrigger. Divide by local mean, remove Q/shape-cell means. Negative bins retained in report and set to zero only for PSD factorization. Flat continuation below5MHz,257-tap Hann-truncated square-root spectrum.',
      'fit':'Shared passive RC grid; acquisition-specific residual spectra. Scalar variance factor fitted to3 original filter means with16 antithetic noise replicas. Mean-shape loss also included. Replica draws reduce response expectation noise, not independent transport.',
      'limits':['Effective residual has no unique microscopic interpretation. Run-specific coefficients are not isotope-dependent gain.',
                'No charge-spectrum shape fit or measured waveform injection. Original MC photon histories, optical parameters and absolute normalization fixed.',
                'Fourier factorization and finite windows omit low-frequency and non-Gaussian structure; internal checks required.'],
      'candidates':{}}
    ROOT.gInterpreter.AddIncludePath(str(PROJECT/'simulation/vendor'))
    ROOT.gInterpreter.Declare('#include "'+str(PROJECT/'simulation/vendor/SiPMResponse.cc')+'"')
    stored={}
    for source,name,run in [('Co60','co60',3),('Am241','am241',12)]:
        with np.load(OUT/f'run{run}_first60.npz') as z:data=dict(z)
        with np.load(OUT/f'{source}_parent.npz') as z:parent=dict(z)
        cfg=json.loads((OUT/f'{source}_base_config.json').read_text());r=cfg['sipm']['readout']
        lsb=(r['adc_max_mV']-r['adc_min_mV'])/2**r['adc_bits']
        f=ROOT.TFile.Open(str(PARENT/name/'events.root'));t=f.Get('Events');t.SetBranchStatus('*',0)
        for key in ('avalanche_t_ns','avalanche_q_C'):t.SetBranchStatus(key,1)
        avalanches=[]
        for idx in parent['ids']:
            t.GetEntry(int(idx));avalanches.append((np.array(t.avalanche_t_ns),np.array(t.avalanche_q_C)))
        f.Close()
        noise=parent['analog_mV']-parent['signal_mV']
        target=data['metrics'][:,:,3].mean(axis=0);targetshape=data['shapes'].mean(axis=0)
        rng=np.random.default_rng(281028310+run)
        innovations=rng.normal(size=(8,len(parent['ids']),2496+256))
        for rc in RCS:
            variant=json.loads(json.dumps(cfg));variant['sipm']['readout']['lowpass_ns']=rc
            native=ROOT.sipm.Config.FromJSON(json.dumps(variant['sipm']))
            signals=[]
            for times,charges in avalanches:
                result=ROOT.sipm.Result()
                for time,q in zip(times,charges):result.avalanche_time_ns.push_back(time);result.avalanche_charge_C.push_back(q)
                result.charge_total_C=float(charges.sum())
                ROOT.sipm.BuildReadout(native,4992.,result)
                signals.append(np.array(result.signal_mV))
            signals=np.array(signals);analog=signals+noise
            if rc==RCS[0]:np.testing.assert_array_equal(signals,parent['signal_mV'])
            adc=np.clip(np.floor((analog-r['adc_min_mV'])/lsb),0,2**r['adc_bits']-1).astype(np.uint16)
            features=wave_features(adc);m=fluctuation_metrics(adc,features['baseline'],features['t10_sample'])[:,:,3]
            d=diagnostic(adc,features,edges)
            excess=data['power'].mean(axis=0)-d['power'].mean(axis=0)
            h=fir_from_power(data['frequency_MHz'],excess)
            perturb=np.array([colored(h,x) for x in innovations])*np.sqrt(np.maximum(signals/lsb,0.))[None,:,:]
            # Exact finite-window expected variance contribution before requantization.
            delta=[]
            for seed in range(8):
                for sign in (-1,1):
                    y=adc.astype(float)+sign*perturb[seed]
                    delta.append(fluctuation_metrics(y,features['baseline'],features['t10_sample'])[:,:,3].mean(axis=0)-m.mean(axis=0))
            added=np.array(delta).mean(axis=0)
            scale=max(0.,float(np.dot(added/target,(target-m.mean(axis=0))/target)/np.dot(added/target,added/target)))
            predicted=m.mean(axis=0)+scale*added
            shapes,kept=aligned_shapes(adc,features);assert len(kept)==len(adc)
            mean=shapes.mean(axis=0);error=np.sqrt(np.mean((mean[REGION]-targetshape[REGION])**2))/targetshape.max()
            relative=predicted/target-1
            # Fixed descriptive score, no likelihood/p-value interpretation.
            score=float(np.mean((relative/.1)**2)+(error/.03)**2)
            row={'base_F':m.mean(axis=0).tolist(),'predicted_F':predicted.tolist(),'target_F':target.tolist(),
                'relative':relative.tolist(),'shape_nrmse':float(error),'variance_scale':scale,
                'variance_per_signal_adc':float(np.dot(h,h)*scale),'score':score,
                'unprojected_residual_power':excess.tolist(),'negative_spectral_bins':int((excess<0).sum())}
            report['candidates'].setdefault(str(rc),{})[source]=row
            stored[(source,rc)]=(h*np.sqrt(scale),variant)
            print(source,rc,'relative',np.round(relative,4),'shape',error,flush=True)
    best=min(RCS,key=lambda rc:sum(v['score'] for v in report['candidates'][str(rc)].values()))
    report['selected_RC_ns']=best;report['selected']={}
    for source,_,run in [('Co60','co60',3),('Am241','am241',12)]:
        h,cfg=stored[(source,best)];variance=float(np.dot(h,h))
        cfg['signal_dependent_noise']={'model':'gaussian_fir_signal_variance',
          'sample_period_ns':2.,'coefficients':(h/np.sqrt(variance)).tolist(),
          'variance_per_signal_adc':variance,'calibration_run':run,
          'parameter_status':'Effective training-only acquisition calibration; not a measured SiPM gain, material property, or uniquely identified electronic mechanism.',
          'provenance':str((OUT/'fit.json').relative_to(PROJECT))}
        cfg['status']='Conditional native waveform calibration; full output must pass held-segment and spectrum checks'
        save(OUT/(source+'_calibrated.json'),cfg)
        report['selected'][source]={'config_sha256':sha(OUT/(source+'_calibrated.json')),**report['candidates'][str(best)][source]}
    save(OUT/'fit.json',report)
    print('Selected shared RC',best,flush=True)


if __name__=='__main__':main()
